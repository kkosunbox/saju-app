/** /g/<slug> 경로에서 slug */
export function guideSlugOf(pathname: string): GuideSlug | undefined {
  const slug = /^\/g\/([^/]+)\/?$/.exec(pathname)?.[1];
  return slug === 'blood' ? 'tarot' : slug && slug in GUIDES ? (slug as GuideSlug) : undefined;
}
