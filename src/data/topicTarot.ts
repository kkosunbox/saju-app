export const TAROT_HAND_SIZE = 5;

export function dealTopicCards() {
  const deck = [...CARDS];
  for (let i = 0; i < TAROT_HAND_SIZE; i++) {
    const swap = i + Math.floor(Math.random() * (deck.length - i));
    [deck[i], deck[swap]] = [deck[swap], deck[i]];
  }
  return deck.slice(0, TAROT_HAND_SIZE);
}
